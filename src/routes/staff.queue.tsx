import { useState } from "react";
import { createFileRoute } from "@tanstack/react-router";
import { Search, Users } from "lucide-react";
import { DataTable, EmptyState, PageHeader, Panel, StatusBadge, inputCls } from "@/components/med/ui";
import { fmtTime, label, setQueueStatus, useStore, type QueueStatus } from "@/lib/store";

export const Route = createFileRoute("/staff/queue")({
  head: () => ({ meta: [{ title: "Patient Queue — MedQueue Staff" }, { name: "description", content: "Manage walk-in patient tokens." }, { property: "og:title", content: "Patient Queue — MedQueue Staff" }, { property: "og:description", content: "Manage walk-in patient tokens." }] }),
  component: StaffQueue,
});

const STATUSES: QueueStatus[] = ["waiting", "in_consultation", "completed", "cancelled"];

function StaffQueue() {
  const queue = useStore((s) => s.queue);
  const [q, setQ] = useState("");
  const [st, setSt] = useState<string>("all");
  const rows = queue.filter((r) => (st === "all" || r.status === st) && (`#${r.token} ${r.patientId}`.toLowerCase().includes(q.trim().toLowerCase())));
  return (
    <>
      <PageHeader title="Patient queue" subtitle={`${queue.filter((r) => r.status === "waiting").length} waiting right now`} />
      <Panel>
        <div className="mb-4 flex flex-col gap-3 sm:flex-row">
          <label className="relative flex-1"><span className="sr-only">Search token or patient</span>
            <Search className="absolute left-3 top-1/2 size-4 -translate-y-1/2 text-muted-foreground" aria-hidden />
            <input className={`${inputCls} pl-9`} placeholder="Search token or patient ID" value={q} onChange={(e) => setQ(e.target.value)} />
          </label>
          <label className="sm:w-52"><span className="sr-only">Filter by status</span>
            <select className={`${inputCls} capitalize`} value={st} onChange={(e) => setSt(e.target.value)}>
              <option value="all">All statuses</option>{STATUSES.map((x) => <option key={x} value={x}>{label(x)}</option>)}
            </select>
          </label>
        </div>
        {rows.length ? (
          <DataTable rows={rows} rowKey={(r) => r.id} cols={[
            { h: "Token", cell: (r) => <span className="font-semibold">#{r.token}</span> },
            { h: "Patient", cell: (r) => r.patientId },
            { h: "Arrived", cell: (r) => fmtTime(r.arrivedAt) },
            { h: "Status", cell: (r) => <StatusBadge status={r.status} /> },
            { h: "Update", cell: (r) => (
              <select aria-label={`Update status for token ${r.token}`} className={`${inputCls} h-9 w-44 capitalize`} value={r.status} onChange={(e) => setQueueStatus(r.id, e.target.value as QueueStatus)}>
                {STATUSES.map((x) => <option key={x} value={x}>{label(x)}</option>)}
              </select>
            ) },
          ]} />
        ) : <EmptyState icon={Users} title={queue.length ? "No matches" : "No patients yet"} text={queue.length ? "Try a different search or filter." : "Tokens generated by students will appear here."} />}
      </Panel>
    </>
  );
}
